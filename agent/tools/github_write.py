def create_pull_request(
    title: str,
    body: str,
    head_branch: str,
    base_branch: str,
) -> str:
    """Create the consolidated security fix pull request.

    Args:
        title: The PR title.
        body: Full markdown PR body. Must contain Closes #N references.
        head_branch: The fix branch to merge from.
        base_branch: The target base branch (default branch).

    Returns:
        JSON string with: pr_number, url.
    """
    data = post(
        f"/repos/{_repo()}/pulls",
        {"title": title, "body": body, "head": head_branch, "base": base_branch},
    )
    return json.dumps({"pr_number": data["number"], "url": data["html_url"]})


def update_pull_request(pr_number: int, title: str, body: str) -> str:
    """Update an existing pull request.

    Args:
        pr_number: The pull request number to update.
        title: The new PR title.
        body: The new full markdown PR body. Must contain Closes #N references.

    Returns:
        JSON string with: pr_number, url.
    """
    data = patch(
        f"/repos/{_repo()}/pulls/{pr_number}",
        {"title": title, "body": body},
    )
    return json.dumps({"pr_number": data["number"], "url": data["html_url"]})


def upsert_seccure_pr(
    state_json: str,
    head_branch: str,
    base_branch: str,
    existing_pr_number: int | None = None,
) -> str:
    """Create or update the single consolidated Seccure PR."""

    state = SeccureState.model_validate_json(state_json)
    title, body = render_pr_title_body(state)
    if existing_pr_number:
        result = update_pull_request(existing_pr_number, title, body)
    else:
        result = create_pull_request(title, body, head_branch, base_branch)
    data = json.loads(result)
    add_labels(data["pr_number"], ["seccure", "auto-fix", "dependabot"])
    return result


def add_labels(pr_number: int, labels: list[str]) -> str:
    """Add labels to a pull request or issue.

    Args:
        pr_number: The PR or issue number.
        labels: List of label name strings to add.

    Returns:
        Confirmation message.
    """
    post(f"/repos/{_repo()}/issues/{pr_number}/labels", {"labels": labels})
    return f"Labels {labels} added to #{pr_number}."


