"""GitHub API write tools used exclusively by the Coordinator agent."""

from __future__ import annotations

import json
import os
import re
from datetime import date

from agent.config import SeccureState
from agent.tools.github_client import get, patch, post

ATTEMPT_MARKER = "<!-- seccure-attempt-count:"
_ATTEMPT_RE = re.compile(r"<!--\s*seccure-attempt-count:(\d+)\s*-->")


def _repo() -> str:
    return os.environ["TARGET_REPO"]


# ---------------------------------------------------------------------------
# Idempotency guard
# ---------------------------------------------------------------------------


def check_existing_seccure_pr() -> str:
    """Check whether an open PR with the 'seccure' label already exists.

    Returns:
        JSON string with: found, pr_number, url, body, and attempt_count.
    """
    repo = _repo()
    prs = get(f"/repos/{repo}/pulls", state="open", per_page=100)
    if not isinstance(prs, list):
        return json.dumps({"found": False, "pr_number": None, "url": None})

    for pr in prs:
        labels = [lb["name"] for lb in pr.get("labels", [])]
        if "seccure" in labels:
            return json.dumps(
                {
                    "found": True,
                    "pr_number": pr["number"],
                    "url": pr["html_url"],
                    "body": pr.get("body") or "",
                    "attempt_count": extract_attempt_count(pr.get("body") or ""),
                }
            )

    return json.dumps(
        {"found": False, "pr_number": None, "url": None, "body": "", "attempt_count": 0}
    )


def extract_attempt_count(body: str) -> int:
    """Read the persisted Seccure retry count from a PR body marker."""

    match = _ATTEMPT_RE.search(body or "")
    return int(match.group(1)) if match else 0


def with_attempt_marker(body: str, attempt_count: int) -> str:
    """Attach or replace the hidden retry marker."""

    marker = f"<!-- seccure-attempt-count:{attempt_count} -->"
    if _ATTEMPT_RE.search(body):
        return _ATTEMPT_RE.sub(marker, body)
    return f"{body.rstrip()}\n\n{marker}\n"


def render_pr_title_body(state: SeccureState) -> tuple[str, str]:
    """Render deterministic Seccure PR title/body from typed state."""

    fixed_rows = []
    for result in state.fix_results:
        if not result.fixed:
            continue
        row_template = (
            "| {package} | {from_version} | {to_version} | "
            "{strategy} | {cve} | {severity} |"
        )
        fixed_rows.append(
            row_template.format(
                package=result.package,
                from_version=result.from_version,
                to_version=result.to_version or "",
                strategy=result.strategy,
                cve=result.cve_id or "",
                severity=result.severity or "",
            )
        )
    if not fixed_rows:
        fixed_rows.append("| _No package changes_ |  |  |  |  |  |")

    conflict_lines = []
    for issue_number in state.conflict_issue_numbers:
        conflict_lines.append(f"- #{issue_number}")

    pr_closes = []
    for pr in state.dependabot_prs:
        pr_number = getattr(pr, "pr_number", None)
        if pr_number:
            pr_closes.append(f"- Closes #{pr_number}")
    if not pr_closes:
        pr_closes.append("- None")

    issue_closes = [
        f"- Closes #{issue.issue_number}" for issue in state.security_issues
    ]
    if not issue_closes:
        issue_closes.append("- None")

    title = "fix(deps): automated Seccure security updates"
    body = f"""## Seccure Automated Security Patch

Auto-generated by the Seccure Agent.

### Packages Fixed
| Package | From | To | Strategy | CVE | Severity |
|---------|------|----|----------|-----|----------|
{chr(10).join(fixed_rows)}
"""

    if conflict_lines:
        body += "\n### Could Not Auto-Fix\n" + "\n".join(conflict_lines) + "\n"

    body += f"""
### Closes Dependabot PRs
{chr(10).join(pr_closes)}

### Closes Issues
{chr(10).join(issue_closes)}

---
PRs created by GITHUB_TOKEN may not trigger CI workflows automatically.
"""
    return title, with_attempt_marker(body, state.attempt_count)


def close_seccure_pr(pr_number: int) -> str:
    """Close an existing Seccure PR with an explanatory comment.

    Args:
        pr_number: The pull request number to close.

    Returns:
        Confirmation message.
    """
    repo = _repo()
    post(
        f"/repos/{repo}/issues/{pr_number}/comments",
        {
            "body": (
                "🔄 **Seccure Agent** is re-running and has superseded this PR.\n\n"
                "A fresh, up-to-date fix PR will be opened shortly."
            )
        },
    )
    patch(f"/repos/{repo}/pulls/{pr_number}", {"state": "closed"})
    return f"Closed existing Seccure PR #{pr_number}."


